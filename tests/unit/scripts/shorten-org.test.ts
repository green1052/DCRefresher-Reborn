// @vitest-environment node
import {describe, expect, it} from "vitest";

import {shortenOrg} from "@/scripts/shorten-org";

describe("shortenOrg", () => {
    it.each([
        // 법인 표기를 빼고 통째로 바꿀 이름.
        ["주식회사 에스케이텔레콤", "SKT"],
        ["(주)엘지유플러스", "LG U+"],
        ["한국과학기술원", "KAIST"],
        // 앞부분 약자는 긴 것부터 맞춘다.
        ["케이티에이치씨엔강서방송", "KT HCN강서방송"],
        ["케이티클라우드", "KT클라우드"],
        ["엔에이치엔클라우드", "NHN클라우드"],
        // 지역·학교·보험 이름.
        ["서울특별시교육청", "서울시교육청"],
        ["경기도수원교육지원청", "수원교육지원청"],
        ["강원특별자치도청", "강원청"],
        ["국립부경대학교", "부경대"],
        ["이화여자대학교", "이화여대"],
        ["서울교육대학교", "서울교대"],
        ["한국교육대학교육연구원", "한국교육대학교육연구원"],
        ["동양생명보험", "동양생명"],
        ["흥국화재해상손해보험", "흥국화재해상손보"]
    ])("%s → %s", (name, short) => {
        expect(shortenOrg(name)).toBe(short);
    });

    it("법인 표기만 있으면 원래 이름을 둔다", () => {
        expect(shortenOrg("주식회사")).toBe("주식회사");
    });
});
